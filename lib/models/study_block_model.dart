class StudyBlockModel {
  const StudyBlockModel({
    required this.id,
    required this.taskId,
    required this.subjectId,
    required this.date,
    required this.startMinute,
    required this.endMinute,
    required this.blockType,
    required this.reason,
    this.status = 'Scheduled',
    this.generatedBy = 'AutoSched Engine',
  });

  factory StudyBlockModel.fromFirestore(String id, Map<String, dynamic> data) {
    return StudyBlockModel(
      id: id,
      taskId: _readString(data, 'taskId', ''),
      subjectId: _readString(data, 'subjectId', ''),
      date: _readDate(data, 'date', DateTime.now()),
      startMinute: _readInt(data, 'startMinute', 18 * 60),
      endMinute: _readInt(data, 'endMinute', 19 * 60),
      blockType: _readString(data, 'blockType', 'Study Block'),
      reason: _readString(data, 'reason', 'Generated by smart scheduler'),
      status: _readString(data, 'status', 'Scheduled'),
      generatedBy: _readString(data, 'generatedBy', 'AutoSched Engine'),
    );
  }

  final String id;
  final String taskId;
  final String subjectId;
  final DateTime date;
  final int startMinute;
  final int endMinute;
  final String blockType;
  final String reason;
  final String status;
  final String generatedBy;

  int get durationMinutes => endMinute - startMinute;

  Map<String, dynamic> toFirestore() {
    return {
      'blockId': id,
      'taskId': taskId,
      'subjectId': subjectId,
      'date': date.toIso8601String(),
      'startMinute': startMinute,
      'endMinute': endMinute,
      'blockType': blockType,
      'reason': reason,
      'status': status,
      'generatedBy': generatedBy,
    };
  }

  StudyBlockModel copyWith({
    String? id,
    String? taskId,
    String? subjectId,
    DateTime? date,
    int? startMinute,
    int? endMinute,
    String? blockType,
    String? reason,
    String? status,
    String? generatedBy,
  }) {
    return StudyBlockModel(
      id: id ?? this.id,
      taskId: taskId ?? this.taskId,
      subjectId: subjectId ?? this.subjectId,
      date: date ?? this.date,
      startMinute: startMinute ?? this.startMinute,
      endMinute: endMinute ?? this.endMinute,
      blockType: blockType ?? this.blockType,
      reason: reason ?? this.reason,
      status: status ?? this.status,
      generatedBy: generatedBy ?? this.generatedBy,
    );
  }
}

String _readString(Map<String, dynamic> data, String key, String fallback) {
  final value = data[key];
  if (value is String && value.trim().isNotEmpty) return value.trim();
  return fallback;
}

int _readInt(Map<String, dynamic> data, String key, int fallback) {
  final value = data[key];
  if (value is int) return value;
  if (value is num) return value.toInt();
  if (value is String) return int.tryParse(value) ?? fallback;
  return fallback;
}

DateTime _readDate(Map<String, dynamic> data, String key, DateTime fallback) {
  final value = data[key];
  if (value is DateTime) return value;
  if (value is String) return DateTime.tryParse(value) ?? fallback;
  final dynamic maybeTimestamp = value;
  try {
    final DateTime converted = maybeTimestamp.toDate() as DateTime;
    return converted;
  } catch (_) {
    return fallback;
  }
}
